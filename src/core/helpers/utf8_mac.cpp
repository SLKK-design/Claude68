static const int kExtToMRCount = (int)(sizeof(kExtToMR)/sizeof(kExtToMR[0]));

unsigned char ToMacRoman(unsigned long cp)
{
    if (cp < 0x80) return (unsigned char)cp;
    if (cp >= 0x00A0 && cp <= 0x00FF) return kLatin1ToMR[cp - 0x00A0];
    int lo = 0, hi = kExtToMRCount - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        if      (kExtToMR[mid].cp == (unsigned short)cp) return kExtToMR[mid].mr;
        else if (kExtToMR[mid].cp  < (unsigned short)cp)  lo = mid + 1;
        else                                               hi = mid - 1;
    }
    return 0;
}

int ReadUTF8(const char* s, int len, unsigned long* cp)
{
    if (len <= 0) { *cp = 0; return 0; }
    unsigned char b0 = (unsigned char)s[0];
    if (b0 < 0x80)  { *cp = b0; return 1; }
    if (b0 < 0xC0)  { *cp = 0; return 1; }
    if (b0 < 0xE0 && len >= 2) {
        /* bad continuation: skip the lead byte, reprocess the next */
        if (((unsigned char)s[1] & 0xC0) != 0x80) { *cp = 0; return 1; }
        *cp = ((b0 & 0x1F) << 6) | ((unsigned char)s[1] & 0x3F);
        return 2;
    }
    if (b0 < 0xF0 && len >= 3) {
        if (((unsigned char)s[1] & 0xC0) != 0x80 ||
            ((unsigned char)s[2] & 0xC0) != 0x80) { *cp = 0; return 1; }
        *cp = ((b0 & 0x0F) << 12) | (((unsigned char)s[1] & 0x3F) << 6)
             | ((unsigned char)s[2] & 0x3F);
        return 3;
    }
    if (len >= 4) { *cp = 0; return 4; }
    *cp = 0; return 1;
}
